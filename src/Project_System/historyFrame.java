public void loadHistoryData() {
    String filePath = "src\\Historyparts.csv";
    File file = new File(filePath);
    
    // Check if the file exists so the program doesn't crash
    if (!file.exists()) {
        txtHistoryLog.setText("No history recorded yet.");
        return;
    }

    try (BufferedReader br = new BufferedReader(new FileReader(file))) {
        txtHistoryLog.setText(""); // Start with a clean slate
        String line;
        while ((line = br.readLine()) != null) {
            // Add the line and a new line break
            txtHistoryLog.append(line + "\n");
        }
    } catch (IOException e) {
        txtHistoryLog.setText("Error loading history: " + e.getMessage());
    }
}

