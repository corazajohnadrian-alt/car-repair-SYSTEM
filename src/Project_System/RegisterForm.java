    private void jButtonRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRegisterActionPerformed
        // TODO add your handling code here:
        String username;
        String password;
        String Email;
        String fullname;
         String role = "";
            
            if (Customercheckbox.isSelected()) {
                role = "Customer";
            } else if (mechaniccheckbox.isSelected()) {
                role = "Mechanic";
            } else if (admincheckbox.isSelected()) {
                role = "Admin";
            } else {
                JOptionPane.showMessageDialog(null, "Please select a role!");
                return;
            }
            
            // Create object using constructor
            user = new User(role);

            JOptionPane.showMessageDialog(null, "Account registered as " + role, "Account rule", JOptionPane.INFORMATION_MESSAGE);
        
        if("".equals(txtusername.getText() )){
            JOptionPane.showMessageDialog(new JFrame(), "Enter an Username", "SYSTEM", JOptionPane.WARNING_MESSAGE);
        }
        if("".equals(txtpassword.getText() )){
            JOptionPane.showMessageDialog(new JFrame(), "Enter an Password", "SYSTEM", JOptionPane.WARNING_MESSAGE);
        }
        if("".equals(txtfullname.getText() )){
            JOptionPane.showMessageDialog(new JFrame(), "Enter your Full Name", "SYSTEM", JOptionPane.WARNING_MESSAGE);
        }
        if("".equals(txtemail.getText() )){
            JOptionPane.showMessageDialog(new JFrame(), "Enter an Email", "SYSTEM", JOptionPane.WARNING_MESSAGE);
        }
        else{
            username = txtusername.getText();
            password = txtpassword.getText();
            Email = txtemail.getText();
            fullname = txtfullname.getText();

           

                String queryRegister = "INSERT INTO accountdetails (accUsername, accPassword, Email, accFullname, acctype) "
                + "VALUES ('" + username + "', '" + password + "', '" + Email + "', '" + fullname + "', '" + role +  "')";
            
            try {
                st.execute(queryRegister);
            } catch (SQLException ex) {
                Logger.getLogger(RegisterForm.class.getName()).log(Level.SEVERE, null, ex);
                
                
            }
            JOptionPane.showMessageDialog(new JFrame(), "You have successfully registered", "SYSTEM", JOptionPane.WARNING_MESSAGE);
            txtusername.setText("");
            txtpassword.setText("");
            txtemail.setText("");
            txtfullname.setText("");
            // Reset profile button
            
            carpic = null;
            
           

        }
    }//GEN-LAST:event_jButtonRegisterActionPerformed

