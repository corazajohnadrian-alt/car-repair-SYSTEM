    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed
        String username;
        String password;

        username = txtusername.getText();
        password = txtpassword.getText();

        //KANI IS CODE NI SA MYSQL
        String querylogin = "Select * from accountdetails where accUsername = '"+ username+  "'"+" And accPassword = '" + password + "'"+";";

        try {
            if (username.trim().isEmpty() || password.trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Enter Username and Password");
                return;
            }
            pst = con.prepareStatement(querylogin);
            ResultSet rs = pst.executeQuery();

            if(!rs.next()) {
                JOptionPane.showMessageDialog(null, "Invalid username or password");
            }
            String role = rs.getString("acctype");
            String user = rs.getString("accUsername");


            JOptionPane.showMessageDialog(null, "Account matched");

            switch (role) {
                case "Customer":
                customerframe customer = new customerframe(user);
                customer.setVisible(true);
                customer.pack();
                customer.setLocationRelativeTo(null);
                this.dispose();
                break;
                case "Mechanic":
                mechanicframe mechanic = new mechanicframe(user);
                mechanic.setVisible(true);
                mechanic.pack();
                mechanic.setLocationRelativeTo(null);
                this.dispose();
                break;
                case "Admin":
                adminframe admin = new adminframe(user);
                admin.setVisible(true);
                admin.pack();
                admin.setLocationRelativeTo(null);
                this.dispose();
                break;
                default:
                JOptionPane.showMessageDialog(null, "Unknown role");

                this.dispose(); // Close login window

            }
        } catch (SQLException ex) {
            Logger.getLogger(LOGIN.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButtonLoginActionPerformed

