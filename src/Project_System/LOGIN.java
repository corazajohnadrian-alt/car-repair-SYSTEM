// Specificaly for the passwordField 
class RoundedPasswordField extends javax.swing.JPasswordField {
    private int cornerRadius = 15;

    public RoundedPasswordField() {
        setOpaque(false); 
        setBorder(null);
    }

    @Override
    public java.awt.Insets getInsets() {
        return new java.awt.Insets(5, 15, 5, 15); // This provides your padding
    }
    
    @Override
    protected void paintComponent(java.awt.Graphics g) {
        java.awt.Graphics2D g2d = (java.awt.Graphics2D) g;
        g2d.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
        
        g2d.setColor(getBackground());
        g2d.fillRoundRect(0, 0, getWidth(), getHeight(), cornerRadius, cornerRadius);
        
        super.paintComponent(g);
    }
}

// round edge Remember preference
class RoundedCheckBox extends javax.swing.JCheckBox {
    public RoundedCheckBox() {
        setOpaque(false);
        setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));
        // This removes the default box and allows us to use custom icons
        setIcon(new javax.swing.ImageIcon(createSimpleIcon(false)));
        setSelectedIcon(new javax.swing.ImageIcon(createSimpleIcon(true)));
    }

    private java.awt.Image createSimpleIcon(boolean selected) {
        java.awt.image.BufferedImage img = new java.awt.image.BufferedImage(18, 18, java.awt.image.BufferedImage.TYPE_INT_ARGB);
        java.awt.Graphics2D g2d = img.createGraphics();
        g2d.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);

        // Draw background
        g2d.setColor(java.awt.Color.WHITE);
        g2d.fillRoundRect(0, 0, 18, 18, 8, 8);

        if (selected) {
            // Draw a simple checkmark or dot in your theme color #6A8D92
            g2d.setColor(java.awt.Color.decode("#6A8D92"));
            g2d.fillRoundRect(4, 4, 10, 10, 4, 4);
        }

        g2d.dispose();
        return img;
    }
}

// Image background
class ImagePanel extends javax.swing.JPanel {
    private java.awt.Image image;

    public ImagePanel() {
    try {
        // Added /resources/ to the path to match your folder structure
        java.net.URL imgURL = getClass().getResource("/Project_System/resources/background.jpg");
        
        if (imgURL != null) {
            image = new javax.swing.ImageIcon(imgURL).getImage();
        } else {
            System.err.println("Still can't find background.jpg! Check if it is really a .jpg");
        }
    } catch (Exception e) {
        e.printStackTrace();
    }
    
}

    @Override
    protected void paintComponent(java.awt.Graphics g) {
        super.paintComponent(g);
        if (image != null) {
            java.awt.Graphics2D g2d = (java.awt.Graphics2D) g;
        
            // 1. High-quality background image rendering
            g2d.setRenderingHint(java.awt.RenderingHints.KEY_INTERPOLATION, java.awt.RenderingHints.VALUE_INTERPOLATION_BILINEAR);
            g2d.setRenderingHint(java.awt.RenderingHints.KEY_ANTIALIASING, java.awt.RenderingHints.VALUE_ANTIALIAS_ON);
            g2d.drawImage(image, 0, 0, getWidth(), getHeight(), this);

            // 2. Define Sidebar and Gradient dimensions
            int width = getWidth();
            int height = getHeight();

            // 3. Define the Multi-Stop Colors
            // Solid-ish black (Alpha 200) for the left sidebar area
            java.awt.Color darkLeft = new java.awt.Color(0, 0, 0, 200); 
            // Theme Teal (Alpha 180) for the middle blend
            java.awt.Color tealMiddle = new java.awt.Color(0, 102, 115, 180);
            // Fully transparent (Alpha 0) for the far right
            java.awt.Color transparentRight = new java.awt.Color(0, 102, 115, 0);

            // 4. Create the Gradient "Stops"
            // 0.0 = Start, 0.4 = End of solid sidebar, 1.0 = Far right edge
            float[] fractions = {0.0f, 0.4f, 1.0f};
            java.awt.Color[] colors = {darkLeft, tealMiddle, transparentRight};

            java.awt.LinearGradientPaint lgp = new java.awt.LinearGradientPaint(
                new java.awt.geom.Point2D.Double(0, 0), 
                new java.awt.geom.Point2D.Double(width, 0),
                fractions, 
                colors
            );

            // 5. Draw the Overlay
            g2d.setPaint(lgp);
            g2d.fillRect(0, 0, width, height);
        }
    }
    
    
}

