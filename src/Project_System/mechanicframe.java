                if (first) { first = false; continue; }
                line = line.trim();
                if (line.isEmpty()) continue;
                String[] cols = line.split(",", -1);
                if (cols.length < 8) continue;
                if (!cols[7].trim().equalsIgnoreCase(mechanicname)) continue;

                String idreq    = cols[6].trim();
