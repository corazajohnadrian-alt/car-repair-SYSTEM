    public void startRefreshingbutton() {
    String name = username;
    System.out.println(username);
    
    javax.swing.Timer refreshTimer = new javax.swing.Timer(1000, e -> {

        StringBuilder sb = new StringBuilder();
        BufferedReader reader = null;
        String line;
        boolean found = false;


        try {
            reader = new BufferedReader(new FileReader(carrepair));

            while ((line = reader.readLine()) != null) {
                String[] row = line.split(",");

                if (row.length >= 8) {

                    if (row[0].equalsIgnoreCase("customerid")) continue; // skip header

                    found = true;

                    String owner = row[1].trim(); // col[1] = ownername

                    if (owner.equalsIgnoreCase(name)) {
                        sb.setLength(0);
                        sb.append("CAR MODEL: ")
                          .append(row[3])          // col[3] = model
                          .append(", PLATE NUM.: ")
                          .append(row[2]);         // col[2] = plateNum

                        String imagePath = row[8].trim(); // col[8] = link/imagePath
                        ImageIcon icon = new ImageIcon(imagePath);
                        Image img = icon.getImage();
                        Image resized = img.getScaledInstance(150, 110, Image.SCALE_SMOOTH);
                        icon = new ImageIcon(resized);
                        
                        
                        servpanel.setHorizontalAlignment(SwingConstants.LEFT);
                        servpanel.setHorizontalTextPosition(SwingConstants.RIGHT);
                        servpanel.setIconTextGap(80);
                        
                        
                        servpanel.setIcon(icon);
                    }
                }
            }

            if (found) {
                
                servpanel.setText(sb.toString());
            } 
        } catch (Exception ex) {
            ex.printStackTrace();
        } finally {
            try {
                if (reader != null) reader.close();
            } catch (IOException ex) {
                ex.printStackTrace();
            }
        }
    });

    refreshTimer.start();
}
    
    // Loads all issues from problems.csv for this customer + mechanic
public void loadIssuesFromCSV() {
    String customer = customerframe.username;
    String mechanic = mechanicframe.mechanicname;

    StringBuilder sb = new StringBuilder();

    try (BufferedReader br = new BufferedReader(new FileReader("src\\problems.csv"))) {
        String line;
        boolean firstRow = true;
        while ((line = br.readLine()) != null) {
            line = line.trim();
            if (line.isEmpty()) continue;
            if (firstRow) { firstRow = false; continue; } // skip header

            // cols: repairmanissuenumber(0), issuenumber(1), username(2),
            //       car(3), problems(4), date(5), idreq(6), repairman(7)
            String[] cols = line.split(",", -1);
            if (cols.length < 8) continue;

            String rowCustomer  = cols[2].trim();
            String rowMechanic  = cols[7].trim();
            String problem      = cols[4].trim();
            String date         = cols[5].trim();

            // Filter: must match BOTH customer AND mechanic
            if (!rowCustomer.equalsIgnoreCase(customer)) continue;
            if (!rowMechanic.equalsIgnoreCase(mechanic)) continue;

            if (sb.length() > 0) sb.append("\n");
            sb.append("• ").append(problem).append("  [").append(date).append("]");
        }
    } catch (IOException ex) {
        ex.printStackTrace();
    }

    ISSUES.setText(sb.length() > 0 ? sb.toString() : "No issues found.");
    ISSUES.setCaretPosition(0);
}

// Loads all requested parts from cartrequest.csv for this customer + mechanic
public void loadPartsFromCSV() {
    String customer = customerframe.username.trim();
    String mechanic = mechanicframe.mechanicname.trim();

    StringBuilder sb = new StringBuilder();

    try (BufferedReader br = new BufferedReader(
            new java.io.InputStreamReader(
                new java.io.FileInputStream("src\\cartrequest.csv"),
                java.nio.charset.StandardCharsets.UTF_8))) {

        String line;
        boolean firstRow = true;

        while ((line = br.readLine()) != null) {
            // Strip BOM if present on first line
            if (firstRow) {
                line = line.replace("\uFEFF", "");
                firstRow = false;
                continue; // skip header
            }

            line = line.trim();
            if (line.isEmpty()) continue;

            // Skip GRAND TOTAL lines — check before split
            if (line.contains("GRAND") || line.contains("grand")) continue;

            String[] cols = line.split(",", -1);
            if (cols.length < 8) continue;

            String partName    = cols[2].trim();
            String rowCustomer = cols[6].trim();
            String rowMechanic = cols[7].trim();

            if (partName.isEmpty()) continue;

            // Case-insensitive match on BOTH customer AND mechanic
            if (!rowCustomer.equalsIgnoreCase(customer)) continue;
            if (!rowMechanic.equalsIgnoreCase(mechanic)) continue;

            String qty   = cols[3].trim();
            String price = cols[4].trim();

            if (sb.length() > 0) sb.append("\n");
            sb.append("• ").append(partName)
              .append("  qty: ").append(qty)
              .append("  ₱").append(price);
        }

    } catch (IOException ex) {
        ex.printStackTrace();
    }

    PARTSREQUESTED.setText(sb.length() > 0 ? sb.toString() : "No parts requested.");
    PARTSREQUESTED.setCaretPosition(0);
}
    // Maps each status to its text area
    private javax.swing.JTextArea getTextAreaForStatus(String status) {
        switch (status.toUpperCase()) {
            case "DIAGNOSING":        return updatestatus;
            case "REQUEST APPROVAL":  return updatestatus;
            case "REPAIRNG":          // typo in your combobox, kept as-is
            case "REPAIRING":         return updatestatus;
            case "QUALITY TESTING":   return updatestatus;
            case "READY FOR PICKUP":  return updatestatus; // appends to same area
            default:                  return null;
        }
    }

    // Loads all saved statuses from CSV for the current customer
    public void loadStatusFromCSV() {
        String customer = customerframe.username;
        File file = new File(updatestatusCSV);
        if (!file.exists()) return;

        String latestStatus = null; // track the last status for color

        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;
            boolean firstRow = true;
            while ((line = br.readLine()) != null) {
                if (firstRow) { firstRow = false; continue; }
                String[] cols = line.split(",", -1);
                // cols: id(0), customer(1), repairman(2), status(3), timestamp(4), idcustomer(5)
                if (cols.length >= 6 &&
                    cols[1].trim().equalsIgnoreCase(customer) &&
                    cols[5].trim().equals(String.valueOf(targetCarSlot))) {
                    String savedStatus = cols[3].trim();
                    String savedTime   = cols[4].trim();
                    javax.swing.JTextArea area = getTextAreaForStatus(savedStatus);
                    if (area != null) {
                        String existing = area.getText();
                        String entry = "[" + savedStatus + "] \n" + savedTime;
                        if (!existing.contains(entry)) {
                            area.append((existing.isEmpty() ? "" : "\n\n") + entry);
                        }
                    }
                    latestStatus = savedStatus; // keep updating — last one wins
                }
            }
        } catch (IOException ex) {
            ex.printStackTrace();
        }

        // Apply color based on the last known status
        if (latestStatus != null) {
            applyStatusColor(latestStatus);
        }
    }

        // Saves the selected status + timestamp to CSV, then updates the text area
        public void saveStatusToCSV(String status, String timestamp) {
            String customer = customerframe.username;
            String repairman = mechanicframe.mechanicname;

            // Get next ID
            int nextId = 1;
            File file = new File(updatestatusCSV);
            boolean fileExists = file.exists();

            if (fileExists) {
                try (BufferedReader br = new BufferedReader(new FileReader(file))) {
                    String line;
                    boolean firstRow = true;
                    while ((line = br.readLine()) != null) {
                        if (firstRow) { firstRow = false; continue; }
                        String[] cols = line.split(",", -1);
                        if (cols.length >= 1) {
                            try { nextId = Math.max(nextId, Integer.parseInt(cols[0].trim()) + 1); }
                            catch (NumberFormatException ignored) {}
                        }
                    }
                } catch (IOException ex) { ex.printStackTrace(); }
            }

            // Append new row to CSV
            try (BufferedWriter bw = new BufferedWriter(new FileWriter(file, true))) {
                if (!fileExists || file.length() == 0) {
bw.write("id,customer,repairman,status,timestamp,idcustomer");                    
bw.newLine();
                }
                bw.write(nextId + "," + customer + "," + repairman + "," + status + "," + timestamp + "," + targetCarSlot);                bw.newLine();
            } catch (IOException ex) {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(this, "Error saving status: " + ex.getMessage());
                return;
            }

            // Update the correct text area immediately
            javax.swing.JTextArea area = getTextAreaForStatus(status);
            if (area != null) {
                String entry = "[" + status + "] " + timestamp;
                String existing = area.getText();
                if (!existing.contains(entry)) {
                    area.append((existing.isEmpty() ? "" : "\n") + entry);
                }
            }
    }

    public void initComboBoxListener() {
        statusbox.addActionListener(e -> {
            String selected = (String) statusbox.getSelectedItem();
            if (selected == null) return;

            // Block any change if already READY FOR PICKUP
            if (isAlreadyFinal()) {
                JOptionPane.showMessageDialog(this,
                    "This service is already READY FOR PICKUP. Status cannot be changed.",
                    "Done", JOptionPane.INFORMATION_MESSAGE);
                return;
            }

            String timestamp = new java.text.SimpleDateFormat("MM/dd/yyyy HH:mm:ss")
                    .format(new java.util.Date());

            saveStatusToCSV(selected, timestamp);
            applyStatusColor(selected);
        });
    }   
    // Checks if this customer already has READY FOR PICKUP saved in CSV
    public boolean isAlreadyFinal() {
        String customer = customerframe.username;
        File file = new File(updatestatusCSV);
        if (!file.exists()) return false;

        try (BufferedReader br = new BufferedReader(new FileReader(file))) {
            String line;
            boolean firstRow = true;
            while ((line = br.readLine()) != null) {
                if (firstRow) { firstRow = false; continue; }
                String[] cols = line.split(",", -1);
                if (cols.length >= 6
        && cols[1].trim().equalsIgnoreCase(customer)
        && cols[5].trim().equals(String.valueOf(targetCarSlot))
        && cols[3].trim().equalsIgnoreCase("READY FOR PICKUP")) {
                    return true;
                }
            }
        } catch (IOException ex) {
            ex.printStackTrace();
        }
        return false;
    }

// Sets servpanel text color based on the current status
    public void applyStatusColor(String status) {
        if (status == null) return;
        switch (status.toUpperCase()) {
            case "DIAGNOSING":
                STATUS2.setForeground(java.awt.Color.ORANGE);
                STATUS2.setText( status);
                statusbox.setSelectedIndex(0);
                break;
            case "REQUEST APPROVAL":
                STATUS2.setForeground(java.awt.Color.BLUE);
                STATUS2.setText( status);
                                statusbox.setSelectedIndex(1);

                break;
            case "REPAIRNG":
            case "REPAIRING":
                STATUS2.setForeground(java.awt.Color.RED);
                STATUS2.setText( status);
                                statusbox.setSelectedIndex(2);

                break;
            case "QUALITY TESTING":
                STATUS2.setForeground(java.awt.Color.MAGENTA);
                STATUS2.setText( status);
                                statusbox.setSelectedIndex(3);

                break;
            case "READY FOR PICKUP":
                STATUS2.setForeground(java.awt.Color.GREEN);
                STATUS2.setText( status);
                                statusbox.setSelectedIndex(4);

                break;
        }
    }
