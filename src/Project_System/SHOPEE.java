        private void addCartListener(JButton btn,
                                  javax.swing.JComboBox<String> combo,
                                  javax.swing.JTextField priceField,
                                  String categoryName) {
        btn.addActionListener(e -> {
            Object sel = combo.getSelectedItem();
            if (sel == null) return;
            String partName = sel.toString();
            int price;
            try {
                price = Integer.parseInt(priceField.getText().trim());
            } catch (NumberFormatException ex) {
                price = 0;
            }
            if (price == 0) return;
            cart.tablecart(categoryName, partName, price); // sends both category + part
        });
    }
    public int readfile(String parts){
    try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(inventory))) {
        String line;
        
        while ((br.readLine()) != null) { // skip header line
            break;
        }
        while ((line = br.readLine()) != null) {
            String[] columns = line.split(",");
            if (columns.length >= 8) {
                String csvPartName = columns[0].trim().toUpperCase();
                
                if (csvPartName.equals(parts.trim().toUpperCase())) {
                    return Integer.parseInt(columns[3].trim());
                }
            }
        }
    } catch (java.io.FileNotFoundException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "CSV file not found: " + inventory);
    } catch (java.io.IOException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error reading CSV: " + ex.getMessage());
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid price format for: " + parts);
    }
    return 0; // return 0 if not found

    }
    
