        private void loadInventoryData() {
        inventoryData.clear();
        try (java.io.BufferedReader br = new java.io.BufferedReader(
                new java.io.FileReader(inventory))) {
            br.readLine(); // skip header
            String line;
            while ((line = br.readLine()) != null) {
                String[] cols = line.split(",");
                if (cols.length < 4) continue;
                String category = cols[0].trim();
                String partName  = cols[1].trim();
                String priceStr  = cols[3].trim();
                inventoryData
                    .computeIfAbsent(category, k -> new ArrayList<>())
                    .add(new String[]{partName, priceStr});
            }
        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Error loading inventory: " + ex.getMessage());
        }
    }

    private void wireCombo(javax.swing.JComboBox<String> combo,
                           javax.swing.JTextField priceField,
                           String csvCategory) {
        combo.removeAllItems();
        List<String[]> rows = inventoryData.get(csvCategory);
        if (rows == null || rows.isEmpty()) {
            combo.addItem("(no data)");
            priceField.setText("0");
            return;
        }
        for (String[] row : rows) {
            combo.addItem(row[0]); // part name
        }
        priceField.setText(rows.get(0)[1]); // set initial price

        combo.addItemListener(e -> {
            if (e.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
                int idx = combo.getSelectedIndex();
                if (idx >= 0 && idx < rows.size()) {
                    priceField.setText(rows.get(idx)[1]);
                }
            }
        });
    }

