    private void savevActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savevActionPerformed


            String ownername = username;
            String plateNum  = txtplatenumber.getText();
            String model     = txtmodel.getText();
            String brand     = txtbrand.getText();
            String year      = txtyear.getText();
            String color     = txtcolor.getText();
            String mileage   = txtmileage.getText();
            String notes     = "";
            String imagePath = (carpic != null) ? carpic.getAbsolutePath() : "";

            if (plateNum.isEmpty() || model.isEmpty() || brand.isEmpty() ||
                year.isEmpty() || color.isEmpty() || mileage.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Please fill all fields!");
                return;
            }

            // Row format: customerid,ownername,plateNum,model,brand,year,color,mileage,link,notes
            String row = customerid + "," + ownername + "," + plateNum + "," + model + "," +
                         brand + "," + year + "," + color + "," + mileage + "," + imagePath + "," + notes;

            try {
                if (mode.equalsIgnoreCase("edit") && editIndex != -1) {
                    java.util.List<String> lines =
                        java.nio.file.Files.readAllLines(new File(file).toPath());
                    lines.set(editIndex, row);
                    java.nio.file.Files.write(new File(file).toPath(), lines);
                    JOptionPane.showMessageDialog(null, "Car updated!");
                } else {
                    try (BufferedWriter writer = new BufferedWriter(new FileWriter(file, true))) {
                        writer.write(row);
                        writer.newLine();
                    }
                    JOptionPane.showMessageDialog(null, "Car added!");
                }
            } catch (Exception e) {
                e.printStackTrace();
            }

            this.dispose();
    }//GEN-LAST:event_savevActionPerformed

