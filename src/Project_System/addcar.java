    public void edit() {
        BufferedReader reader = null;
        try {
            reader = new BufferedReader(new FileReader(file));
            String line;
            int index = 0;

            while ((line = reader.readLine()) != null) {
                String[] data = line.split(",", -1);

                // skip header
                if (data[0].equalsIgnoreCase("customerid")) { index++; continue; }

                // match by customerid (col[0])
                if (data.length >= 9 &&
                    data[0].trim().equals(String.valueOf(customerid))) {

                    txtplatenumber.setText(data[2].trim()); // plateNum
                    txtmodel.setText(data[3].trim());       // model
                    txtbrand.setText(data[4].trim());       // brand
                    txtyear.setText(data[5].trim());        // year
                    txtcolor.setText(data[6].trim());       // color
                    txtmileage.setText(data[7].trim());     // mileage

                    if (data.length >= 9 && !data[8].trim().isEmpty()) {
                        carpic = new File(data[8].trim());
                        if (carpic.exists()) {
                            ImageIcon icon = new ImageIcon(data[8].trim());
                            Image img = icon.getImage()
                                           .getScaledInstance(452, 194, Image.SCALE_SMOOTH);
                            image.setText("");
                            image.setIcon(new ImageIcon(img));
                        }
                    }

                    editIndex = index;
                    break;
                }
                index++;
            }
        } catch (Exception e) {
            e.printStackTrace();
        } finally {
            try { if (reader != null) reader.close(); } catch (Exception ex) {}
        }
    }    
