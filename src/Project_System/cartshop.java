    private void saveDeductLog(DefaultTableModel model) {
    java.io.File file = new java.io.File("src\\deductinventory.csv");
    boolean isNew = !file.exists() || file.length() == 0;

    try (java.io.PrintWriter pw = new java.io.PrintWriter(
            new java.io.FileWriter(file, true))) {

        if (isNew) pw.println("category,parts,qtyused");

        for (int i = 0; i < model.getRowCount(); i++) {
            String category = model.getValueAt(i, 1).toString().trim(); // col 1 = category
            String part     = model.getValueAt(i, 2).toString().trim(); // col 2 = part name
            String qty      = model.getValueAt(i, 3).toString().trim(); // col 3 = qty
            pw.printf("%s,%s,%s%n", category, part, qty);
        }

    } catch (java.io.IOException e) {
        e.printStackTrace();
    }
}
    
    private void deductFromInventory(DefaultTableModel model) {
        String inventoryPath = "src\\INVENTORY.csv";
        java.io.File file = new java.io.File(inventoryPath);
        if (!file.exists()) {
            javax.swing.JOptionPane.showMessageDialog(this, "INVENTORY.csv not found!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Read all inventory lines
        java.util.List<String> lines = new java.util.ArrayList<>();
        try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(file))) {
            String line;
            while ((line = br.readLine()) != null) {
                lines.add(line);
            }
        } catch (java.io.IOException e) {
            e.printStackTrace();
            return;
        }

        // For each cart row, find matching part in inventory and deduct qty
        for (int i = 0; i < model.getRowCount(); i++) {
            String partName = model.getValueAt(i, 2).toString().trim();
            int qtyToDeduct = Integer.parseInt(model.getValueAt(i, 3).toString().trim());

            for (int j = 1; j < lines.size(); j++) { // skip header (j=0)
                String[] cols = lines.get(j).split(",", -1);
                if (cols.length < 3) continue;
                if (cols[1].trim().equalsIgnoreCase(partName)) {
                    int currentQty = 0;
                    try { currentQty = Integer.parseInt(cols[2].trim()); } catch (Exception ignored) {}
                    int newQty = Math.max(0, currentQty - qtyToDeduct);
                    cols[2] = String.valueOf(newQty);

                    // Update Status based on Threshold
                    if (cols.length > 5 && !cols[5].trim().isEmpty()) {
                        try {
                            int threshold = Integer.parseInt(cols[5].trim());
                            cols[4] = newQty <= threshold ? "Low Stock" : "";
                        } catch (Exception ignored) {}
                    }

                    lines.set(j, String.join(",", cols));
                    break;
                }
            }
        }

        // Write updated lines back to INVENTORY.csv
        try (java.io.BufferedWriter bw = new java.io.BufferedWriter(new java.io.FileWriter(file, false))) {
            for (String line : lines) {
                bw.write(line);
                bw.newLine();
            }
        } catch (java.io.IOException e) {
            e.printStackTrace();
        }
    }
    
    
    private void sendrequestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sendrequestActionPerformed
        JOptionPane.showMessageDialog(this, "REQUEST ADDED");
        
        
    DefaultTableModel model = (DefaultTableModel) carttable.getModel();

        if (model.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Cart is empty!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        java.io.File file = new java.io.File(csvPath);
        boolean isNew = !file.exists();

        // ✅ Count how many times this customer already sent a request
        int customerid = 1;
        if (!isNew) {
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(file))) {
                String line;
                while ((line = br.readLine()) != null) {
                    if (line.contains("GRAND TOTAL")) {
                        String[] cols = line.split(",");
                        // cols[5] = customer, cols[6] = mechanic
                        if (cols.length > 6
                            && cols[5].trim().equalsIgnoreCase(customerUsername)
                            && cols[6].trim().equalsIgnoreCase(mechanicName)) {
                            customerid++; // ✅ found a previous request from same customer+mechanic
                        }
                    }
                }
            } catch (java.io.IOException e) {
                e.printStackTrace();
            }
        }

        try (java.io.BufferedWriter bw = new java.io.BufferedWriter(new java.io.FileWriter(file, true))) {

            // Write header only if file is new
            if (isNew) {
                bw.write("orderId,category,part,qty,price,total,customer,mechanic,customerid");
                bw.newLine();
            }

            // Write each row
            for (int i = 0; i < model.getRowCount(); i++) {
                String orderId  = model.getValueAt(i, 0).toString();
                String category = model.getValueAt(i, 1).toString();
                String part     = model.getValueAt(i, 2).toString();
                String qty      = model.getValueAt(i, 3).toString();
                String price    = model.getValueAt(i, 4).toString();
                String total    = model.getValueAt(i, 5).toString();

                bw.write(orderId + "," + category + "," + part + "," + qty + "," + price + "," + total
                       + "," + customerUsername + "," + mechanicName + "," + customerid);
                bw.newLine();
            }

            // Grand total row
            bw.write(",,,,GRAND TOTAL: " + jLabel2.getText()
                    + "," + customerUsername + "," + mechanicName + "," + customerid);
            bw.newLine();
            bw.write("---,---,---,---,---,---,---,---,---");     
            bw.newLine();

            deductFromInventory(model);
            saveDeductLog(model); // ← also log to deductinventory.csv
            javax.swing.JOptionPane.showMessageDialog(this, "Request sent successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
            model.setRowCount(0);
            jLabel2.setText("₱0");

        } catch (java.io.IOException e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to save: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
        
    
    }//GEN-LAST:event_sendrequestActionPerformed

    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
             int row = carttable.getSelectedRow();

                if (row != -1) {

                    int confirm = JOptionPane.showConfirmDialog(
                        null,
                        "Remove \"" + carttable.getValueAt(row, 2) + "\" from cart?", // Part Name
                        "Delete Item",
                        JOptionPane.YES_NO_OPTION
                    );

                    if (confirm == JOptionPane.YES_OPTION) {

                        DefaultTableModel model = (DefaultTableModel) carttable.getModel();
                        model.removeRow(row);

                        // Re-number IDs
                        for (int i = 0; i < model.getRowCount(); i++) {
                            model.setValueAt(i + 1, i, 0);
                        }

                        updateTotal();
                    }
                }
    }//GEN-LAST:event_deleteActionPerformed

