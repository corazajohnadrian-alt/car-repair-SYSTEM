    // New 3-argument version: takes category, specific part, and price
    public void tablecart(String categoryName, String partName, int price) {
        DefaultTableModel model = (DefaultTableModel) carttable.getModel();
        // Column indices: 0=OrderID, 1=Category, 2=Part, 3=Qty, 4=UnitPrice, 5=Total
        for (int i = 0; i < model.getRowCount(); i++) {
            Object val = model.getValueAt(i, 2); // check Part column
            if (val == null || val.toString().isEmpty()) continue;
            if (val.toString().equalsIgnoreCase(partName)) {
                int qty = Integer.parseInt(model.getValueAt(i, 3).toString());
                qty++;
                model.setValueAt(qty, i, 3);
                model.setValueAt(price * qty, i, 5);
                updateTotal();
                return;
            }
        }
        int orderId = model.getRowCount() + 1;
        model.addRow(new Object[]{orderId, categoryName, partName, 1, price, price});
        updateTotal();
    }

    // Keep old 2-argument version for backward compatibility
    public void tablecart(String partName, int price) {
        tablecart(partName, partName, price);
    }
    
    public void updateTotal() {
        DefaultTableModel model = (DefaultTableModel) carttable.getModel();
        int total = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
                Object val = model.getValueAt(i, 5); // Column 5 = Total (shifted by new Part column)         
                total += Integer.parseInt(val.toString());
            }
        
        jLabel2.setText("₱" + total);
    }
